  id integer generated by default as identity primary key,
  question text not null unique check (char_length(question) between 5 and 200),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.daily_answers (
  member_id uuid not null references public.members(id) on delete cascade,
  question_day date not null,
  question_id integer not null references public.daily_questions(id) on delete cascade,
  answer text not null check (char_length(answer) between 1 and 150),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (member_id, question_day)
);
create index if not exists daily_answers_day_idx on public.daily_answers(question_day, updated_at desc);

