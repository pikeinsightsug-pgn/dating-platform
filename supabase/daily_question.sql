-- member functions; no existing table, column, function or member row is changed.
-- Apply after smart_discovery.sql. Run once in the Supabase SQL Editor.
--
-- How it works:
--   * One light question is shown to every member each day (Botswana time). The questions
--     rotate through the list below; the owner can add more rows to daily_questions at any time.
--   * An approved member answers in up to 150 characters, and can change the answer that day.
--   * Only after answering can a member see how others answered, and only answers from members
--     they are already allowed to see in Discover (approved, 18+, not blocked either way).
--   * Answers return only first name, age, city, country and photo path: never email, phone,
--     partner preferences or anything else private.
