-- Today's date in Botswana (Uganda is one hour ahead, close enough for a daily question).
create or replace function public.daily_question_today()
returns date language sql stable set search_path = ''
as $$ select (now() at time zone 'Africa/Gaborone')::date $$;
revoke all on function public.daily_question_today() from public, anon, authenticated;

-- The question for a given day: rotates through the active questions in a fixed order.
create or replace function public.daily_question_for(p_day date)
returns table (id integer, question text)
language sql stable security definer set search_path = ''
as $$
  with active as (
    select q.id, q.question, row_number() over (order by q.id) - 1 as position, count(*) over () as total
    from public.daily_questions q where q.active
  )
  select a.id, a.question from active a
  where a.position = ((p_day - date '2026-01-01') % a.total + a.total) % a.total
$$;
revoke all on function public.daily_question_for(date) from public, anon, authenticated;

create or replace function public.todays_question()
returns table (question_id integer, question text, question_day date, my_answer text, answer_count integer)
language plpgsql stable security definer set search_path = ''
as $$
declare
  me uuid := public.require_approved_member();
  today date := public.daily_question_today();
begin
  return query
  select q.id, q.question, today,
         (select a.answer from public.daily_answers a where a.member_id = me and a.question_day = today),
         (select count(*)::integer from public.daily_answers a where a.question_day = today)
  from public.daily_question_for(today) q;
end;
$$;

create or replace function public.answer_daily_question(p_answer text)
returns boolean
language plpgsql volatile security definer set search_path = ''
as $$
declare
  me uuid := public.require_approved_member();
  today date := public.daily_question_today();
  clean text := regexp_replace(trim(coalesce(p_answer, '')), '\s+', ' ', 'g');
  qid integer;
begin
  if char_length(clean) < 1 or char_length(clean) > 150 then
    raise exception 'Answers must be between 1 and 150 characters' using errcode = '22023';
  end if;
  select q.id into qid from public.daily_question_for(today) q;
  if qid is null then
    return false;
  end if;
  insert into public.daily_answers (member_id, question_day, question_id, answer)
  values (me, today, qid, clean)
  on conflict (member_id, question_day)
  do update set answer = excluded.answer, question_id = excluded.question_id, updated_at = now();
  return true;
end;
$$;

-- Other members' answers for today, visible only once the caller has answered.
create or replace function public.todays_answers(p_limit integer default 30, p_offset integer default 0)
returns table (
  member_id uuid, first_name text, age integer, city text, location text,
  profile_photo_path text, is_official boolean, answer text, answered_at timestamptz
)
language plpgsql stable security definer set search_path = ''
as $$
declare
  me uuid := public.require_approved_member();
  today date := public.daily_question_today();
begin
  if not exists (select 1 from public.daily_answers a where a.member_id = me and a.question_day = today) then
    return;
  end if;
  return query
  select m.id, m.first_name, m.age, m.city, m.location,
         case
           when m.profile_photo_url is not null
            and (storage.foldername(m.profile_photo_url))[1] = m.user_id::text
           then m.profile_photo_url
         end,
         coalesce(m.is_official, false),
         a.answer, a.updated_at
  from public.daily_answers a
  join public.members m on m.id = a.member_id
  where a.question_day = today
    and a.member_id <> me
    and m.approved = true and m.age >= 18 and m.user_id is not null
    and public.members_share_audience(me, m.id)
    and not public.members_are_blocked(me, m.id)
  order by coalesce(m.is_official, false) desc, (m.profile_photo_url is not null) desc, a.updated_at desc, m.id
  limit least(50, greatest(1, coalesce(p_limit, 30))) offset greatest(0, coalesce(p_offset, 0));
end;
$$;

